import { useEffect, useState } from "react";
import { Button } from "@/components/ui/button";
import { Combobox } from "@/components/ui/combobox";
import {
  Dialog,
  DialogContent,
  DialogDescription,
  DialogFooter,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Input } from "@/components/ui/input";
import { Label } from "@/components/ui/label";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { Switch } from "@/components/ui/switch";
import { useBatches, useCreateCourseBatch, useUpdateCourseBatch } from "@/hooks/use-batches";
import { useCourses } from "@/hooks/use-courses";
import type { CourseBatch, CourseBatchPayload } from "@/types";

interface FormState {
  name: string;
  course: string;
  batch: string;
  start_date: string;
  end_date: string;
  is_active: boolean;
}

const EMPTY: FormState = {
  name: "",
  course: "",
  batch: "",
  start_date: "",
  end_date: "",
  is_active: true,
};

/** Create/edit a course batch — a course run tied to a time slot and date range. */
export function CourseBatchDialog({
  open,
  onClose,
  courseBatch,
}: {
  open: boolean;
  onClose: () => void;
  courseBatch: CourseBatch | null; // null = create
}) {
  const [form, setForm] = useState<FormState>(EMPTY);
  const [courseSearch, setCourseSearch] = useState("");

  const coursesQ = useCourses(1, 50, courseSearch);
  const batchesQ = useBatches({ page_size: 100, is_active: true });
  const create = useCreateCourseBatch();
  const update = useUpdateCourseBatch();
  const saving = create.isPending || update.isPending;

  useEffect(() => {
    if (!open) return;
    setCourseSearch("");
    setForm(
      courseBatch
        ? {
            name: courseBatch.name,
            course: String(courseBatch.course),
            batch: courseBatch.batch == null ? "" : String(courseBatch.batch),
            start_date: courseBatch.start_date ?? "",
            end_date: courseBatch.end_date ?? "",
            is_active: courseBatch.is_active,
          }
        : EMPTY,
    );
  }, [open, courseBatch]);

  const set = <K extends keyof FormState>(k: K, v: FormState[K]) =>
    setForm((f) => ({ ...f, [k]: v }));

  function submit(e: React.FormEvent) {
    e.preventDefault();
    if (!form.name.trim() || !form.course || !form.batch) return;
    const payload: CourseBatchPayload = {
      name: form.name.trim(),
      course: Number(form.course),
      batch: Number(form.batch),
      start_date: form.start_date || null,
      end_date: form.end_date || null,
      is_active: form.is_active,
    };
    if (courseBatch) {
      update.mutate({ id: courseBatch.id, payload }, { onSuccess: () => onClose() });
    } else {
      create.mutate(payload, { onSuccess: () => onClose() });
    }
  }

  const dateRangeInvalid =
    !!form.start_date && !!form.end_date && form.end_date < form.start_date;

  return (
    <Dialog open={open} onOpenChange={(o) => !o && onClose()}>
      <DialogContent className="sm:max-w-lg">
        <DialogHeader>
          <DialogTitle>{courseBatch ? `Edit ${courseBatch.name}` : "New course batch"}</DialogTitle>
          <DialogDescription>
            {courseBatch
              ? `Course batch ID ${courseBatch.coursebatch_id} — generated by the backend and not editable.`
              : "The course batch ID (e.g. PY-2026-001) is generated once you save."}
          </DialogDescription>
        </DialogHeader>
        <form onSubmit={submit} className="space-y-4">
          <div className="grid gap-4 sm:grid-cols-2">
            <div className="grid gap-2 sm:col-span-2">
              <Label htmlFor="cohort-name" required>Name</Label>
              <Input
                id="cohort-name"
                required
                placeholder="Python Bootcamp"
                value={form.name}
                onChange={(e) => set("name", e.target.value)}
              />
            </div>

            <div className="grid gap-2">
              <Label required>Course</Label>
              <Combobox
                value={form.course}
                onChange={(v) => set("course", v)}
                options={(coursesQ.data?.results ?? []).map((c) => ({
                  value: String(c.id),
                  label: c.name,
                }))}
                onSearchChange={setCourseSearch}
                loading={coursesQ.isFetching}
                selectedLabel={courseBatch?.course_name ?? undefined}
                placeholder="Select course"
                searchPlaceholder="Search courses…"
                emptyText="No courses found."
              />
            </div>

            <div className="grid gap-2">
              <Label required>Time slot</Label>
              <Select value={form.batch} onValueChange={(v) => set("batch", v)}>
                <SelectTrigger>
                  <SelectValue placeholder="Select time slot" />
                </SelectTrigger>
                <SelectContent>
                  {(batchesQ.data?.results ?? []).map((b) => (
                    <SelectItem key={b.id} value={String(b.id)}>
                      {b.name}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
            </div>

            <div className="grid gap-2">
              <Label htmlFor="cohort-start">Start date</Label>
              <Input
                id="cohort-start"
                type="date"
                value={form.start_date}
                onChange={(e) => set("start_date", e.target.value)}
              />
            </div>
            <div className="grid gap-2">
              <Label htmlFor="cohort-end">End date</Label>
              <Input
                id="cohort-end"
                type="date"
                min={form.start_date || undefined}
                value={form.end_date}
                onChange={(e) => set("end_date", e.target.value)}
              />
            </div>

            <div className="flex items-center gap-2 sm:col-span-2">
              <Switch
                id="cohort-active"
                checked={form.is_active}
                onCheckedChange={(c) => set("is_active", c)}
              />
              <Label htmlFor="cohort-active">Active</Label>
            </div>
          </div>

          {dateRangeInvalid && (
            <p className="text-destructive text-xs">End date cannot be before the start date.</p>
          )}
          {/* unique_together on (course, batch, start_date) — surfaced via the error toast. */}

          <DialogFooter>
            <Button type="button" variant="outline" onClick={onClose}>
              Cancel
            </Button>
            <Button
              type="submit"
              variant="brand"
              disabled={saving || !form.course || !form.batch || dateRangeInvalid}
            >
              {saving ? "Saving…" : courseBatch ? "Save changes" : "Create course batch"}
            </Button>
          </DialogFooter>
        </form>
      </DialogContent>
    </Dialog>
  );
}
