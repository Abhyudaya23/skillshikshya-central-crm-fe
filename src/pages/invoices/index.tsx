import {
  ChevronLeft,
  ChevronRight,
  FileText,
  MailCheck,
  MoreHorizontal,
  Search,
  Send,
} from "lucide-react";
import { useEffect, useMemo, useState } from "react";
import { Badge } from "@/components/ui/badge";
import { Button } from "@/components/ui/button";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import { Input } from "@/components/ui/input";
import {
  Select,
  SelectContent,
  SelectItem,
  SelectTrigger,
  SelectValue,
} from "@/components/ui/select";
import { Skeleton } from "@/components/ui/skeleton";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { useAuth } from "@/context/auth";
import { useDataSource } from "@/context/data-source";
import { useInvoices, useResendInvoice } from "@/hooks/use-invoices";
import { formatDateTime, formatNPR } from "@/lib/leads-format";
import type { InvoiceListParams, InvoiceType } from "@/types/invoices";
import { InvoiceEmailConfigDialog } from "./email-config-dialog";

const PAGE_SIZE = 25;

const TYPE_TONE: Record<InvoiceType, string> = {
  enrollment: "bg-sky-500/15 text-sky-700 dark:text-sky-300",
  payment: "bg-emerald-500/15 text-emerald-700 dark:text-emerald-300",
};

/**
 * Invoice register — `GET /api/invoices/`.
 * Documents are generated by the backend (student creation / successful payment),
 * so this page is read-only apart from the admin re-send and CC config.
 */
export default function InvoicesPage() {
  const { source } = useDataSource();
  const isApi = source === "api";
  const { user } = useAuth();
  const isStaff = !!user?.is_staff;

  const [page, setPage] = useState(1);
  const [type, setType] = useState<"all" | InvoiceType>("all");
  const [from, setFrom] = useState("");
  const [to, setTo] = useState("");
  const [search, setSearch] = useState("");
  const [configOpen, setConfigOpen] = useState(false);

  useEffect(() => setPage(1), [type, from, to]);

  const params = useMemo<InvoiceListParams>(
    () => ({
      page,
      page_size: PAGE_SIZE,
      type: type === "all" ? undefined : type,
      created_at__gte: from ? `${from}T00:00:00Z` : undefined,
      created_at__lte: to ? `${to}T23:59:59Z` : undefined,
    }),
    [page, type, from, to],
  );

  const { invoices, count, isLoading } = useInvoices(params);
  const resend = useResendInvoice();

  // The endpoint has no ?search — filter the loaded page client-side instead.
  const rows = useMemo(() => {
    const q = search.trim().toLowerCase();
    if (!q) return invoices;
    return invoices.filter((i) =>
      `${i.invoice_number} ${i.student_name ?? ""} ${i.course_name ?? ""} ${i.emailed_to ?? ""}`
        .toLowerCase()
        .includes(q),
    );
  }, [invoices, search]);

  const totalPages = Math.max(1, Math.ceil(count / PAGE_SIZE));

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-start justify-between gap-3">
        <div>
          <p className="text-brand font-mono text-[11px] font-bold tracking-wider uppercase">Finance</p>
          <h1 className="font-headline mt-1 text-3xl font-semibold tracking-tight">Invoices</h1>
          <p className="text-muted-foreground mt-1 text-sm">
            Course-fee documents and payment receipts. Generated automatically and emailed to the
            student — never created by hand.
          </p>
        </div>
        {isApi && isStaff && (
          <Button variant="outline" onClick={() => setConfigOpen(true)}>
            <MailCheck /> Email settings
          </Button>
        )}
      </div>

      {!isApi ? (
        <div className="text-muted-foreground rounded-2xl border border-dashed py-16 text-center text-sm">
          Invoices are a live-backend feature. Toggle to <span className="font-semibold">Live</span>{" "}
          in the header.
        </div>
      ) : (
        <div className="bg-card overflow-hidden rounded-2xl border shadow-[0_1px_3px_0_rgba(0,0,0,0.05),0_1px_2px_-1px_rgba(0,0,0,0.05)]">
          <div className="flex flex-wrap items-center gap-2 border-b p-4">
            <div className="relative min-w-[15rem] flex-1">
              <Search className="text-muted-foreground absolute top-2.5 left-3 size-4" />
              <Input
                placeholder="Search invoice no., student, course, or email"
                className="rounded-full pl-9"
                value={search}
                onChange={(e) => setSearch(e.target.value)}
              />
            </div>
            <Select value={type} onValueChange={(v) => setType(v as "all" | InvoiceType)}>
              <SelectTrigger className="h-9 w-44">
                <SelectValue />
              </SelectTrigger>
              <SelectContent>
                <SelectItem value="all">All types</SelectItem>
                <SelectItem value="enrollment">Course fee</SelectItem>
                <SelectItem value="payment">Payment receipt</SelectItem>
              </SelectContent>
            </Select>
            <Input
              type="date"
              className="h-9 w-40"
              value={from}
              onChange={(e) => setFrom(e.target.value)}
              title="Created on or after"
            />
            <Input
              type="date"
              className="h-9 w-40"
              value={to}
              onChange={(e) => setTo(e.target.value)}
              title="Created on or before"
            />
          </div>

          <div className="overflow-x-auto">
            <Table>
              <TableHeader>
                <TableRow>
                  <TableHead>Invoice</TableHead>
                  <TableHead>Type</TableHead>
                  <TableHead>Student</TableHead>
                  <TableHead>Course</TableHead>
                  <TableHead className="text-right">Amount</TableHead>
                  <TableHead className="text-right">Remaining</TableHead>
                  <TableHead>Emailed</TableHead>
                  <TableHead>Created</TableHead>
                  <TableHead className="w-12" />
                </TableRow>
              </TableHeader>
              <TableBody>
                {isLoading &&
                  Array.from({ length: 5 }).map((_, i) => (
                    <TableRow key={i}>
                      <TableCell colSpan={9}>
                        <Skeleton className="h-6 w-full" />
                      </TableCell>
                    </TableRow>
                  ))}
                {!isLoading && rows.length === 0 && (
                  <TableRow>
                    <TableCell colSpan={9} className="py-14 text-center">
                      <FileText className="text-muted-foreground mx-auto size-8 opacity-40" />
                      <p className="mt-2 text-sm font-semibold">No invoices found</p>
                      <p className="text-muted-foreground text-xs">
                        They appear once a student is created or a successful payment is recorded.
                      </p>
                    </TableCell>
                  </TableRow>
                )}
                {rows.map((i) => (
                  <TableRow key={i.id}>
                    <TableCell className="font-mono text-xs font-semibold">
                      {i.invoice_number}
                    </TableCell>
                    <TableCell>
                      <Badge variant="secondary" className={TYPE_TONE[i.type]}>
                        {i.type_display ?? (i.type === "payment" ? "Payment Receipt" : "Course Fee")}
                      </Badge>
                    </TableCell>
                    <TableCell className="font-medium">{i.student_name || "—"}</TableCell>
                    <TableCell className="text-muted-foreground">{i.course_name || "—"}</TableCell>
                    <TableCell className="text-right font-medium tabular-nums">
                      {formatNPR(Number(i.amount))}
                    </TableCell>
                    <TableCell className="text-right tabular-nums">
                      {formatNPR(Number(i.remaining_balance))}
                    </TableCell>
                    <TableCell className="text-sm">
                      {i.sent_at ? (
                        <div className="min-w-0">
                          <p className="truncate">{i.emailed_to}</p>
                          <p className="text-muted-foreground text-xs">{formatDateTime(i.sent_at)}</p>
                          {i.cc_emails?.length > 0 && (
                            <p className="text-muted-foreground text-xs">
                              cc {i.cc_emails.length}
                            </p>
                          )}
                        </div>
                      ) : (
                        <span className="text-muted-foreground text-xs">Not sent</span>
                      )}
                    </TableCell>
                    <TableCell className="text-muted-foreground whitespace-nowrap">
                      {formatDateTime(i.created_at)}
                    </TableCell>
                    <TableCell>
                      <DropdownMenu>
                        <DropdownMenuTrigger asChild>
                          <Button variant="ghost" size="icon" className="rounded-full">
                            <MoreHorizontal />
                          </Button>
                        </DropdownMenuTrigger>
                        <DropdownMenuContent align="end">
                          <DropdownMenuItem
                            disabled={!i.pdf_url}
                            onSelect={() => i.pdf_url && window.open(i.pdf_url, "_blank")}
                          >
                            {i.pdf_url ? "Open PDF" : "No PDF archived"}
                          </DropdownMenuItem>
                          {isStaff && (
                            <DropdownMenuItem
                              disabled={resend.isPending}
                              onSelect={() => resend.mutate(i.id)}
                            >
                              <Send className="size-4" /> Re-send email
                            </DropdownMenuItem>
                          )}
                        </DropdownMenuContent>
                      </DropdownMenu>
                    </TableCell>
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          </div>

          {count > PAGE_SIZE && (
            <div className="bg-muted/50 flex items-center justify-between border-t px-6 py-3">
              <span className="text-muted-foreground text-sm">
                Page {page} of {totalPages} · {count} invoices
              </span>
              <div className="flex items-center gap-2">
                <Button
                  variant="ghost"
                  size="icon"
                  disabled={page <= 1}
                  onClick={() => setPage((p) => p - 1)}
                >
                  <ChevronLeft />
                </Button>
                <Button
                  variant="ghost"
                  size="icon"
                  disabled={page >= totalPages}
                  onClick={() => setPage((p) => p + 1)}
                >
                  <ChevronRight />
                </Button>
              </div>
            </div>
          )}
        </div>
      )}

      <InvoiceEmailConfigDialog open={configOpen} onOpenChange={setConfigOpen} />
    </div>
  );
}
